function normalizeSourceValue(value: unknown): string {
  return typeof value === "string" ? value.trim().toLocaleLowerCase("en-US").replace(/[\s-]+/g, "_") : "";
}

export function poiTaxonomyIdForSourceValues(sourceClass: unknown, category: unknown, sourceId?: unknown): AtlasPlaceTypeId | null {
  const id = typeof sourceId === "string" ? sourceId.trim() : "";
  if (id && id in POI_SOURCE_ID_OVERRIDES) return POI_SOURCE_ID_OVERRIDES[id as keyof typeof POI_SOURCE_ID_OVERRIDES];
  const normalizedClass = normalizeSourceValue(sourceClass);
  if (normalizedClass && normalizedClass in POI_SOURCE_CLASS_TO_TAXONOMY) return POI_SOURCE_CLASS_TO_TAXONOMY[normalizedClass as PoiSourceClass];
  const normalizedCategory = normalizeSourceValue(category);
  if (normalizedCategory && normalizedCategory in POI_COARSE_CATEGORY_FALLBACKS) return POI_COARSE_CATEGORY_FALLBACKS[normalizedCategory as keyof typeof POI_COARSE_CATEGORY_FALLBACKS];
  return null;
}

export function poiTaxonomyIdForProperties(properties: Record<string, unknown>): AtlasPlaceTypeId | null {
  return poiTaxonomyIdForSourceValues(
    properties.fclass ?? properties.class ?? properties.type ?? properties.amenity ?? properties.shop ?? properties.tourism ?? properties.leisure ?? properties.office ?? properties.healthcare ?? properties.historic ?? properties.natural,
    properties.category,
    properties.id
  );
}
